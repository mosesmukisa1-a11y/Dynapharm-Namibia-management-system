// Offline source codemod ONLY. No hooks, loader, eval, DB, target environment
// inspection, process restart, or runtime translation. Outputs reviewable source.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {compileSqlDescriptors} from './lib/sql-descriptor-compiler.mjs';
const root=process.cwd(),out='generated-artifacts/sql-runtime-enforcement-final';
if((await fs.readFile('api/services/registeredSqlCatalog.js','utf8')).length>200)
  throw Error('Source migration already applied; do not regenerate the registered catalog from migrated source');
const compiled=await compileSqlDescriptors(root);
await fs.mkdir(out+'/source-candidates',{recursive:true});
await fs.writeFile(out+'/source-migration-review.json',JSON.stringify({
  tool:'offline source migration, never runtime enforcement',
  issues:compiled.issues,locations:compiled.locations,fileInputs:compiled.fileInputs,
  admittedDefinitions:Object.keys(compiled.catalog).length,
},null,2));
if(compiled.issues.length){
  console.log(JSON.stringify({status:'SOURCE MIGRATION REJECTED',issues:compiled.issues.length}));
  process.exitCode=1;
}else{
  const manifest=[];
  for(const [absolute,entry]of compiled.modules){
    const file=path.relative(root,absolute),target=out+'/source-candidates/'+file;
    await fs.mkdir(path.dirname(target),{recursive:true});
    await fs.writeFile(target,entry.source+'\n');
    manifest.push({file,candidate:target,beforeSha256:entry.sourceSha256,
      afterSha256:createHash('sha256').update(entry.source+'\n').digest('hex')});
  }
  const entries=Object.entries(compiled.catalog),parts=[];
  for(let i=0;i<entries.length;i+=100){
    const name='part-'+String(parts.length+1).padStart(2,'0')+'.js',file='api/services/registeredSql/'+name;
    const candidate=out+'/source-candidates/'+file,source='// Immutable fixed SQL definitions; generated by offline source migration.\nexport default '+JSON.stringify(Object.fromEntries(entries.slice(i,i+100)),null,2)+';\n';
    await fs.mkdir(path.dirname(candidate),{recursive:true});await fs.writeFile(candidate,source);
    manifest.push({file,candidate,beforeSha256:null,afterSha256:createHash('sha256').update(source).digest('hex')});parts.push(name);
  }
  const target=out+'/source-candidates/api/services/registeredSqlCatalog.js';
  await fs.writeFile(target,'// Fixed repository SQL catalog. Generated offline; never extended at runtime.\n'+
    parts.map((p,i)=>`import p${i} from './registeredSql/${p}';`).join('\n')+
    '\nexport default Object.freeze({'+parts.map((_,i)=>`...p${i}`).join(',')+'});\n');
  manifest.push({file:'api/services/registeredSqlCatalog.js',candidate:target,
    beforeSha256:createHash('sha256').update(await fs.readFile('api/services/registeredSqlCatalog.js')).digest('hex'),
    afterSha256:createHash('sha256').update(await fs.readFile(target)).digest('hex')});
  await fs.writeFile(out+'/source-migration-manifest.json',JSON.stringify({files:manifest},null,2));
  console.log(JSON.stringify({status:'SOURCE CANDIDATES PREPARED',files:manifest.length,definitions:Object.keys(compiled.catalog).length}));
}
