// Sanitized per-finding reasoning. Never copies source snippets or scanner messages.
import fs from 'node:fs/promises';
import path from 'node:path';
import {parse} from '@babel/parser';
const out='generated-artifacts/security-remediation-closure';
const scans=JSON.parse(await fs.readFile(out+'/scanner-summary.json','utf8'));
function walk(n,fn){if(!n||typeof n!=='object')return;fn(n);for(const[k,v]of Object.entries(n)){
  if(['loc','extra','start','end'].includes(k))continue;
  if(Array.isArray(v))v.forEach(x=>walk(x,fn));else if(v&&typeof v==='object')walk(v,fn);}}
const rows=[];
for(const f of scans.find(s=>s.scanner==='sast')?.results||[]){
  const file=path.relative(process.cwd(),f.location.path),line=f.location.start.line;
  let classification='unresolved',reason='Needs complete reachable-call-path review; no blanket suppression.';
  const tree=parse(await fs.readFile(file,'utf8'),{sourceType:'module',plugins:['jsx']});
  if(f.rule.includes('pg-express')){
    const calls=[];walk(tree,n=>{if(n.type==='CallExpression'&&
      n.callee?.type==='MemberExpression'&&n.callee.property?.name==='query'&&
      n.loc.start.line<=line&&n.loc.end.line>=line)calls.push(n);});
    const call=calls.sort((a,b)=>(a.end-a.start)-(b.end-b.start))[0],arg=call?.arguments[0];
    if(arg?.type==='StringLiteral'||arg?.type==='TemplateLiteral'&&arg.expressions.length===0){
      classification='false positive with code-level justification';
      reason=call.arguments.length>1?
        'Exact flagged query SQL is a static literal/template with no interpolation; runtime values are supplied separately in pg parameter arguments.':
        'Exact flagged query is static SQL with no runtime interpolation or request-derived SQL text.';
    }else if(file==='api/db.js'&&line===167){
      classification='false positive with code-level justification';
      reason='insert() validates every column and table with sanitizeIdentifier ASCII identifier regex; values use numbered pg bindings.';
    }else if(file==='api/distributor-agreement.js'){
      classification='false positive with code-level justification';
      reason='distCols derives exclusively from locally constructed fixed distData keys, not spread/request keys; distPlaceholders generates numeric bindings and distVals is separate.';
    }else if(file==='api/services/saleEvidenceRepair.js'){
      classification='false positive with code-level justification';
      reason='Flagged interpolated table is from the local two-entry stock_movements/branch_inventory_movements constant tuple; IDs/patch JSON remain bound parameters.';
    }else if(file==='scripts/seed_catalog.js'){
      classification='false positive with code-level justification';
      reason='SQL variable is a local static INSERT/ON CONFLICT literal (insertProductText/insertImageText/insertDistributorText); catalogue values use pg bindings. CLI tool, not an HTTP handler.';
    }else if(file==='api/services/stockCostLayers.js'){
      classification='false positive with code-level justification';
      reason='Flagged line is canonicalProductUnit(): imported query() receives a static product_unit_config SELECT with $1 binding; scanner reports a call boundary, not concatenation.';
    }else if(file==='api/db.js'){
      reason='Generic query(text,params) executor is reachable from many production APIs. This review cannot establish taint safety for every caller; wrapper alone is not proof. Retain CRITICAL blocker.';
    }
  }else if(f.rule.includes('object-assign')){
    classification='false positive with code-level justification';
    reason='Object.assign target is a newly allocated Error and source is a fixed local single status/statusCode property. No assignment of arbitrary request keys to an existing shared object/prototype.';
  }else if(f.rule.includes('fs-express')){
    classification='false positive with code-level justification';
    reason=file.includes('audit-predeployment')?
      'Read-only CLI source auditor load(file), no Express handler or HTTP entry; traverses locally selected repository source imports. Not executed on untrusted HTTP paths.':
      'CLI writes generated-artifacts/sale-repair/<numeric time>-<fixed mode>.json. No request-controlled path; audited apply/dry-run modes are operator-only. Not executed in this remediation.';
  }else if(f.rule.includes('bcrypt')){
    classification='false positive with code-level justification';
    reason='bcrypt.hash receives a variable generated by randomBytes(24), with cost 12; no hardcoded credential string. Legacy fixture was not executed in this closure.';
  }else if(f.rule.includes('weak-algorithm')){
    classification='false positive with code-level justification';
    reason='SHA-1 only derives stable non-secret product/image catalogue IDs; never used for password/reset/session integrity. Changing IDs here would risk historical identity breakage.';
  }
  rows.push({file,line,rule:f.rule,severity:f.severity,classification,reason});
}
for(const v of scans.find(s=>s.scanner==='dependency')?.vulnerabilities||[]){
  const version=JSON.parse(await fs.readFile('node_modules/xlsx/package.json','utf8')).version;
  const fixed=v.id.includes('4r6h')?'0.19.3':'0.20.2';
  rows.push({file:'package-lock.json / node_modules/xlsx/package.json',line:null,rule:v.id,severity:'HIGH',
    classification:version==='0.20.3'?'false positive with code-level justification':'unresolved',
    reason:`Official CDN SheetJS installed version ${version}, lockfile URL pins 0.20.3. Advisory description identifies ${fixed} as fixed; scanner affected range introduced:0 has no upper bound. No dependency/lockfile change or broad suppression. This is advisory/version reconciliation, not a general arbitrary spreadsheet safety guarantee.`});
}
await fs.writeFile(out+'/scanner-triage.json',JSON.stringify(rows,null,2));
await fs.writeFile(out+'/scanner-triage.md','# Candidate scanner triage\n\n'+
  'Every reported location is listed individually. No scanner exclusion was added. Static parameterization conclusions apply to the exact flagged statement, not every endpoint in its file. A generic SQL executor remains unresolved. Privacy scan returned zero findings; that is not proof of absence. Legacy CLI tools classified as non-HTTP are not claimed retired.\n\n'+
  rows.map((r,i)=>`## ${i+1}. ${r.file}:${r.line??'dependency'}\n\n- Rule: ${r.rule}\n- Severity: ${r.severity}\n- Classification: **${r.classification}**\n- Reason: ${r.reason}\n`).join('\n'));
console.log(JSON.stringify({findings:rows.length,unresolved:rows.filter(r=>r.classification==='unresolved').length}));
